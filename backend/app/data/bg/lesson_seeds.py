def get_lesson_seed(level: str, unit_id: str, lesson_type: str) -> dict | None:
    """Return unit-specific Bulgarian lesson content for A2-C2."""
    skill = str(lesson_type).lower()
    item = _UNITS.get(str(unit_id))
    if item is None or item[0] != str(level).upper() or skill not in _SKILLS:
        return None

    level, title, text, grammar = item
    words = _WORDS[unit_id]
    base = {
        "title": title,
        "objective": f"Развийте българския си език на ниво {level} чрез темата „{title}“.",
        "unit_id": unit_id,
        "source": "curated_bulgarian",
        "words": words,
        "vocabulary_words": [word[0] for word in words],
        "grammar": grammar,
        "examples": [text],
    }

    if skill == "grammar":
        base["objective"] = f"Използвайте правилно {', '.join(grammar)} в контекста на темата „{title}“."
        base["examples"] = [text, words[0][2], words[1][2]]
    elif skill == "vocabulary":
        base["objective"] = "Усвойте ключовите думи и ги използвайте самостоятелно в изречения."
    elif skill == "reading":
        base.update(
            text=text,
            questions=_READING_QUESTIONS[unit_id],
        )
    elif skill == "listening":
        base.update(
            transcript=text,
            questions=_READING_QUESTIONS[unit_id],
        )
    elif skill == "speaking":
        base.update(
            prompt=f"Говорете 1–2 минути по темата „{title}“. Използвайте поне три ключови думи и една граматична конструкция от урока.",
            phrases=[text, words[0][2], "Според мен е важно да разгледаме въпроса от няколко гледни точки."],
        )
    elif skill == "writing":
        base.update(
            prompt=f"Напишете 100–140 думи по темата „{title}“, като използвате поне три ключови думи.",
            guidance=["Използвайте граматичната конструкция на урока.", "Свържете идеите логично.", "Проверете съгласуването и правописа."],
        )
    else:
        base.update(
            questions=[
                f"Обяснете с ваши думи основната граматична тема: {', '.join(grammar)}.",
                "Напишете две изречения с две нови думи.",
                "Съставете кратък пример от реална ситуация.",
            ]
        )
    return base
