def get_lesson_seed(level: str, unit_id: str, lesson_type: str) -> dict | None:
    """Return Bulgarian lesson content for a known A2-C2 curriculum unit."""
    skill = str(lesson_type).lower()
    item = _UNITS.get(str(unit_id))
    if item is None or item[0] != str(level).upper() or skill not in _SKILLS:
        return None
    level, title, text = item
    words = _WORDS[unit_id]
    base = {
        "title": title,
        "objective": f"Развийте уменията си по български език на ниво {level} по темата „{title}“.",
        "unit_id": unit_id,
        "source": "curated_bulgarian",
        "words": words,
        "vocabulary_words": [word[0] for word in words],
        "grammar": [],
        "examples": [text],
    }
    if skill == "grammar":
        base.update(objective="Употребявайте граматичните конструкции в контекст.", grammar=["target-structures"], examples=[text, "Ако имах повече време, бих прочел още една статия."])
    elif skill == "vocabulary":
        base["objective"] = "Усвоете ключовите думи и ги използвайте в изречения."
    elif skill == "reading":
        base.update(text=text, questions=["Каква е основната идея на текста?", "Посочете две ключови думи от текста.", "Какво заключение можете да направите?"])
    elif skill == "listening":
        base.update(transcript=text, questions=["Каква е основната тема?", "Коя информация е най-важна?", "Кои две думи разпознахте?"])
    elif skill == "speaking":
        base.update(prompt=f"Говорете по темата „{title}“. Използвайте поне три думи от урока.", phrases=[text, "Според мен това зависи от ситуацията.", "Бих искал да добавя още един аргумент."], examples=[text])
    elif skill == "writing":
        base.update(prompt=f"Напишете кратък свързан текст по темата „{title}“.", guidance=["Използвайте поне три думи от урока.", "Свържете идеите с подходящи съюзи.", "Проверете граматиката и правописа."], examples=[text])
    else:
        base.update(questions=["Обяснете основната граматична конструкция.", "Съставете две изречения с думите от урока.", "Обобщете темата със свои думи."])
