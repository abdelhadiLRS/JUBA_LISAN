def _unit(unit_id: str, level: str):
    return next((u for u in CURRICULUM.get(level, []) if u.id == unit_id), None)

def get_lesson_seed(level: str, unit_id: str, lesson_type: str) -> dict | None:
    level = str(level).upper()
    skill = str(lesson_type).lower()
    unit = _unit(unit_id, level)
    content = _CONTENT.get(unit_id)
    if unit is None or content is None or skill not in _SKILLS:
        return None

    words = content["words"]
    base = {
        "title": unit.title,
        "objective": f"Развијте знање српског језика на нивоу {level} кроз тему „{unit.title}“.",
        "unit_id": unit_id,
        "source": "curated_serbian",
        "grammar": list(unit.grammar_points),
        "words": words,
        "vocabulary_words": [word[0] for word in words],
        "examples": [content["text"]],
    }

    if skill == "grammar":
        base["objective"] = f"Употребите граматичке структуре „{', '.join(unit.grammar_points)}“ у контексту теме „{unit.title}“."
    elif skill == "vocabulary":
        base["objective"] = f"Усвојите кључни речник за тему „{unit.title}“ и употребите га у контексту."
    elif skill == "reading":
        base["text"] = content["text"]
        base["questions"] = content["questions"]
    elif skill == "listening":
        base["transcript"] = content["text"]
        base["questions"] = content["questions"]
    elif skill == "speaking":
        base["prompt"] = content["prompt"]
        base["phrases"] = [word[2] for word in words]
        base["examples"] = [content["text"]]
    elif skill == "writing":
        base["prompt"] = content["prompt"]
        base["guidance"] = [
            f"Употребите структуру: {', '.join(unit.grammar_points)}.",
            "Употребите најмање три речи из циљног речника.",
            "Повежите идеје јасним и логичним реченицама.",
        ]
        base["examples"] = [content["text"]]
    elif skill == "review":
        base["questions"] = content["questions"][:]
        base["questions"].append(f"Објасните како тема „{unit.title}“ користи циљну граматику.")
    return base
